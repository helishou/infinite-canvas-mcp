import assert from "node:assert/strict";
import { chromium } from "playwright";

const browser = await chromium.launch({ channel: "msedge", headless: true });
try {
    const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
    const errors = [];
    page.on("pageerror", error => errors.push(error.message));
    page.on("pageerror", error => console.error(error.stack));
    await page.route("http://127.0.0.1:17370/**", route => route.fulfill({ status: 503, json: { ok: false } }));
    await page.goto(`${process.env.CANVAS_TEST_URL || "http://localhost:3001"}/tests/h3-formal-editing.html`);
    const evidence = () => page.getByTestId("formal-evidence").textContent().then(JSON.parse);
    await Promise.race([page.getByLabel("Clip prompt").waitFor(), new Promise((_, reject) => page.once("pageerror", reject))]).catch(async error => { console.error({ errors, page: (await page.locator("body").innerText()).slice(0, 1800) }); throw error; });
    assert.deepEqual((await evidence()).writes, [], "mount and StrictMode must preserve the compiled prompt and references");
    await page.getByRole("button", { name: "Refresh source event", exact: true }).click();
    await page.getByRole("button", { name: "Toggle theme", exact: true }).click();
    assert.deepEqual((await evidence()).writes, [], "source events and theme changes must not rewrite formal Clips");
    const original = await page.getByLabel("Clip prompt").inputValue();
    const edited = original.replace("Hero waits.", "Hero turns toward the door.");
    await page.getByLabel("Clip prompt").fill(edited);
    await page.getByRole("button", { name: "Run Clip", exact: true }).click();
    await page.waitForFunction(() => JSON.parse(document.querySelector('[data-testid="formal-evidence"]').textContent).runs.length === 1);
    const state = await evidence();
    assert.equal(state.runs[0].prompt, edited);
    assert.equal(state.flushes, 1);
    assert.equal(state.runs[0].referenceBindings[0].storageKey, "image:approved");
    assert.equal(state.segment.productionClipProjection.inputHash, "original-compiled-input");
    assert.equal(state.writes.length, 1, "only the explicit manual text edit may write");
    assert.deepEqual(errors, []);
    await page.goto(`${process.env.CANVAS_TEST_URL || "http://localhost:3001"}/tests/h3-formal-recovery.html`);
    const retry = page.getByRole("button", { name: "重新提交 1 个手动编辑", exact: true });
    await retry.waitFor({ timeout: 10000 }).catch(async error => { console.error({ errors, page: (await page.locator("body").innerText()).slice(0, 2200), evidence: await page.evaluate(() => window.formalRecoveryFixture?.evidence()) }); throw error; });
    assert.equal(await retry.isEnabled(), true);
    assert.equal((await page.evaluate(() => window.formalRecoveryFixture.evidence())).submissions.length, 0);
    await retry.click();
    await page.waitForFunction(() => window.formalRecoveryFixture.evidence().submissions.length === 1);
    const recovered = await page.evaluate(() => window.formalRecoveryFixture.evidence());
    assert.equal(recovered.project.nodes[0].metadata.segments[0].prompt, "Preserved manual prompt");
    assert.equal(recovered.project.nodes[0].metadata.segments[0].result, "historical.mp4");
    await retry.waitFor({ state: "hidden" });
    assert.deepEqual(await page.evaluate(() => window.formalRecoveryFixture.outbox()), []);
    assert.deepEqual(errors, []);
    await page.goto(`${process.env.CANVAS_TEST_URL || "http://localhost:3001"}/tests/h3-formal-recovery.html?hashFailure=1`);
    const retryBackend = page.getByRole("button", { name: "重新提交 1 个已保留操作", exact: true });
    await retryBackend.waitFor();
    assert.equal(await retryBackend.isEnabled(), true);
    assert.equal((await page.evaluate(() => window.formalRecoveryFixture.evidence())).submissions.length, 0);
    await retryBackend.click();
    await page.waitForFunction(() => window.formalRecoveryFixture.evidence().submissions.length === 1);
    const backendRecovered = await page.evaluate(() => window.formalRecoveryFixture.evidence());
    assert.equal(backendRecovered.project.nodes[0].metadata.segments[0].prompt, "Preserved manual prompt");
    assert.equal(backendRecovered.project.nodes[0].metadata.segments[0].result, "historical.mp4");
    await retryBackend.waitFor({ state: "hidden" });
    assert.deepEqual(await page.evaluate(() => window.formalRecoveryFixture.outbox()), []);
    assert.deepEqual(errors, []);
    console.log("PASS: H3 manual edits and explicit recovery of formal/hash-failure drafts preserve inputs and history without automatic resubmission");
} finally { await browser.close(); }
