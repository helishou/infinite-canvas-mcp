import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { chromium } from "playwright";

const browser = await chromium.launch({ channel: "msedge", headless: true });
try {
    const page = await browser.newPage({ viewport: { width: 1320, height: 1040 } });
    const errors = [];
    page.on("pageerror", (error) => errors.push(error.message));
    await page.route("http://127.0.0.1:17370/**", (route) => route.fulfill({ status: 503, json: { ok: false } }));
    await page.goto(`${process.env.CANVAS_TEST_URL || "http://localhost:3001"}/tests/continuity-readable.html`);
    const panel = page.locator("[data-continuity-workspace]");
    await panel.getByText("翠子 · 抓握状态", { exact: true }).waitFor();
    const visibleText = () => panel.innerText();
    const evidence = () => page.getByTestId("continuity-evidence").textContent().then(JSON.parse);
    assert.match(await visibleText(), /尚未抓住顺子的手臂/);
    assert.match(await visibleText(), /蒙太奇的第一天/);
    assert.match(await visibleText(), /篮中保留原有鸡蛋/);
    assert.doesNotMatch(await visibleText(), /F_GRIP|object_kind|allowed_values|SC02_REPAIR/);
    assert.equal(await panel.getByRole("textbox", { name: "事实 ID" }).isVisible(), false);
    await panel.locator("[data-continuity-entry=facts]").first().getByText("技术详情", { exact: true }).click();
    assert.match(await panel.locator("pre").first().innerText(), /F_GRIP/);
    await panel.locator("[data-continuity-entry=facts]").first().getByText("技术详情", { exact: true }).click();

    await panel.getByRole("button", { name: "发生的变化 1", exact: true }).click();
    assert.match(await visibleText(), /变化前[\s\S]*尚未抓住顺子的手臂[\s\S]*变化后[\s\S]*左手握住顺子的右上臂/);
    assert.match(await visibleText(), /翠子伸手抓住顺子/);
    assert.doesNotMatch(await visibleText(), /EV_GRIP|source_anchor|before/);
    await panel.getByRole("button", { name: "对象状态", exact: true }).click();
    assert.match(await visibleText(), /镜头开始时[\s\S]*镜头结束时/);
    assert.doesNotMatch(await visibleText(), /F_GRIP|"start"|"end"/);
    await panel.getByRole("button", { name: "问题 · 1", exact: true }).click();
    assert.match(await visibleText(), /左手握住顺子的右上臂/);
    assert.doesNotMatch(await visibleText(), /CONTINUITY_STATE_MISMATCH|F_GRIP|SH01|SH02|SEG02|source\.ledger/);
    await panel.getByRole("button", { name: "定位对象 · 顺子回头看向翠子" }).first().click();
    assert.deepEqual((await evidence()).locations[0], { kind: "shot", id: "SH02" });
    await panel.getByRole("button", { name: "交给导演修复" }).click();
    assert.ok((await evidence()).handoffs[0].instruction.includes('"factId": "F_GRIP"'));
    await panel.getByRole("button", { name: "镜头衔接", exact: true }).click();
    assert.match(await visibleText(), /翠子 · 抓握状态：左手握住顺子的右上臂 → 尚未抓住顺子的手臂/);

    await panel.getByRole("button", { name: "剧情状态", exact: true }).click();
    await panel.getByRole("button", { name: "关注事项 3", exact: true }).click();
    await panel.getByRole("button", { name: "保存连续性源稿", exact: true }).click();
    const saved = (await evidence()).saves[0];
    assert.equal(saved.facts[0].id, "F_GRIP");
    assert.equal(saved.facts[0].allowed_values[1], "holding the child's arm");
    assert.equal(saved.events[0].after, "holding the child's arm");
    const images = join(tmpdir(), "canvas-continuity-readable");
    await mkdir(images, { recursive: true });
    await page.screenshot({ path: join(images, "continuity-light.png"), animations: "disabled" });
    await page.getByRole("button", { name: "Theme", exact: true }).click();
    await page.waitForFunction(() => document.documentElement.classList.contains("dark") && getComputedStyle(document.querySelector('[data-continuity-workspace] nav[aria-label="已登记账本项"] button')).color.startsWith("rgba(255, 255, 255"));
    await page.screenshot({ path: join(images, "continuity-dark.png"), animations: "disabled" });
    await panel.screenshot({ path: join(images, "continuity-dark-panel.png"), animations: "disabled" });
    await page.getByRole("button", { name: "Language", exact: true }).click();
    await panel.getByRole("button", { name: "Story states", exact: true }).waitFor();
    assert.doesNotMatch(await visibleText(), /director\.workspace\./);
    await page.setViewportSize({ width: 430, height: 920 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
    await page.screenshot({ path: join(images, "continuity-narrow.png"), animations: "disabled" });
    await page.getByRole("button", { name: "Readonly", exact: true }).click();
    assert.equal(await panel.getByRole("button", { name: "Save continuity source", exact: true }).count(), 0);
    assert.equal(await panel.getByText("Edit continuity manually", { exact: true }).count(), 0);
    assert.equal(await panel.locator("[data-continuity-entry]").count(), 3);
    await page.getByRole("button", { name: "Readonly", exact: true }).click();
    const thirdFact = panel.locator("[data-continuity-entry=facts]").nth(2);
    await thirdFact.getByText("Technical details", { exact: true }).click();
    await thirdFact.getByRole("button", { name: "Remove", exact: true }).click();
    assert.equal(await panel.locator("[data-continuity-entry=facts]").count(), 2);
    assert.equal((await evidence()).saves.length, 1, "removal remains an unsaved local edit");
    await panel.getByRole("button", { name: "Save continuity source", exact: true }).click();
    const afterRemoval = (await evidence()).saves[1];
    assert.deepEqual(afterRemoval.facts.map(({ id }) => id), ["F_GRIP", "F_DAY"]);
    assert.equal(afterRemoval.requirements[0].fact_id, "F_EGGS", "dependent references remain for the checker to diagnose");
    assert.deepEqual(errors, []);
    console.log(`PASS: readable facts, changes, shot states, diagnostics, canonical save/handoff/locate, readonly, languages, themes and narrow modal\nScreenshots: ${images}`);
} finally {
    await browser.close();
}
