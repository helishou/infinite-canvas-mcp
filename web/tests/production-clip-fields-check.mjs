import assert from "node:assert/strict";
import { chromium } from "playwright";

const browser = await chromium.launch({ channel: "msedge", headless: true });
try {
    const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } });
    const errors = [];
    page.on("pageerror", error => errors.push(error.message));
    await page.route("http://127.0.0.1:17370/**", route => route.fulfill({ status: 503, json: { ok: false } }));
    await page.goto(`${process.env.CANVAS_TEST_URL || "http://localhost:3001"}/tests/acheng-production.html?scenario=clip-fields`);
    await page.getByRole("button", { name: "Clip 组合", exact: true }).click();
    const card = page.locator('[data-clip-source-fields="SEG1"]');
    await card.waitFor({ state: "visible" });
    assert.equal(await page.locator('[data-translation-progress]').count(), 0);
    assert.equal(await card.locator('[data-source-json-editor]').count(), 0);
    assert.ok((await page.locator('[data-clip-source-list]').boundingBox()).y < 600, "Clip content should be visible before scrolling past duplicate status lists");
    const evidence = () => page.getByLabel("evidence").textContent().then(JSON.parse);
    const original = structuredClone((await evidence()).director.source.segments);
    assert.equal((await evidence()).saves, 0);
    for (const text of [original[0].summary, original[0].overall_soundscape, original[0].non_diegetic_music, "single continuous take", "信使音色", "码头环境"]) {
        assert.ok((await card.innerText()).includes(text), `Missing visible Clip field: ${text}`);
    }
    assert.ok((await page.locator('[data-clip-source-fields="SEG2"]').innerText()).includes("未设置"));
    await card.getByRole("button", { name: "编辑内容", exact: true }).click();
    await card.getByRole("textbox", { name: "配乐", exact: true }).fill("REJECT_SAVE");
    await card.getByRole("button", { name: "保存", exact: true }).click();
    await card.getByRole("alert").waitFor();
    assert.equal(await card.getByRole("textbox", { name: "配乐", exact: true }).inputValue(), "REJECT_SAVE");
    assert.deepEqual((await evidence()).director.source.segments, original);
    await card.getByRole("textbox", { name: "配乐", exact: true }).fill("N/A");
    await page.getByRole("button", { name: "分镜", exact: true }).click();
    await page.getByRole("button", { name: "Clip 组合", exact: true }).click();
    await card.getByRole("button", { name: "编辑内容", exact: true }).click();
    assert.equal(await card.getByRole("textbox", { name: "配乐", exact: true }).inputValue(), "N/A");
    await card.getByRole("button", { name: "保存", exact: true }).click();
    await card.getByRole("button", { name: "编辑内容", exact: true }).waitFor();
    const saved = (await evidence()).director.source.segments;
    assert.deepEqual(saved, [{ ...original[0], non_diegetic_music: "N/A" }, original[1]]);
    await card.getByRole("button", { name: "编辑 运动要求", exact: true }).click();
    await card.getByRole("textbox", { name: "动作密度", exact: true }).fill("3 beats / 5s");
    await page.getByRole("button", { name: "更新测试参考核验", exact: true }).click();
    await card.getByRole("button", { name: "保存", exact: true }).click();
    await card.getByRole("button", { name: "编辑 运动要求", exact: true }).waitFor();
    const merged = (await evidence()).director.source.segments[0];
    assert.equal(merged.execution_gate, "Independently updated reference check");
    assert.equal(merged.motion_profile.beat_density, "3 beats / 5s");
    assert.equal(merged.non_diegetic_music, "N/A");
    assert.deepEqual((await evidence()).director.source.segments[1], original[1]);
    const header = page.locator('[data-production-clip-id="SEG1"] .storyboard-clip-heading');
    await header.getByRole("button", { name: "锁定片段 1", exact: true }).click();
    await header.getByRole("button", { name: "解锁片段 1", exact: true }).waitFor();
    assert.equal((await evidence()).director.source.segments[0].locked, true);
    await header.getByRole("button", { name: "解锁片段 1", exact: true }).click();
    await header.getByRole("button", { name: "锁定片段 1", exact: true }).waitFor();
    assert.equal((await evidence()).director.source.segments[0].locked, false);
    await page.getByRole("button", { name: "Edit Clip style", exact: true }).click();
    assert.ok((await card.innerText()).includes("N/A"));
    assert.ok((await card.innerText()).includes(original[0].summary));
    await page.getByRole("button", { name: "theme", exact: true }).click();
    await page.getByRole("button", { name: "language", exact: true }).click();
    await page.getByRole("button", { name: "Clip grouping", exact: true }).click();
    await page.setViewportSize({ width: 440, height: 950 });
    await card.getByRole("button", { name: "Edit content", exact: true }).waitFor();
    assert.ok((await card.innerText()).includes("Overall soundscape"));
    assert.ok((await card.innerText()).includes("single continuous take"));
    const fieldOverflow = await card.evaluate(element => element.scrollWidth > element.clientWidth + 1);
    assert.equal(fieldOverflow, false);
    assert.deepEqual(errors, []);
    console.log("PASS: expanded v2 Clip fields, empty values, failure retention, draft recovery, scoped save, independent edits merged, focused Clip, English/dark/narrow layout; no writes while viewing");
} finally { await browser.close(); }
