import assert from "node:assert/strict";
import { chromium } from "playwright";
import fs from "node:fs";
const base = process.env.CANVAS_TEST_WEB || "http://127.0.0.1:3001";
const browser = await chromium.launch({ headless: true });
try {
    const page = await browser.newPage({ viewport: { width: 900, height: 850 } });
    const errors = [];
    page.on("pageerror", error => errors.push(error.message));
    for (const scenario of ["empty", "empty-error"]) {
        await page.goto(`${base}/tests/director-subagents.html?scenario=${scenario}`);
        await page.waitForFunction(() => window.__subagentFixture?.calls.some(call => call.action === "list"));
        await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
        assert.equal(await page.getByTestId("agent-subagents").count(), 0, "empty/error-only conversations must reserve no subagent UI");
    }
    await page.goto(`${base}/tests/director-subagents.html`);
    const header = page.getByRole("button", { name: /^子代理任务/ });
    await header.waitFor();
    assert.equal(await header.getAttribute("aria-expanded"), "false");
    assert.equal(await page.getByTestId("agent-subagent").count(), 0, "the compact roster starts collapsed");
    const positions = await header.locator("svg, span").evaluateAll(elements => elements.map(element => element.getBoundingClientRect().top + element.getBoundingClientRect().height / 2));
    assert.ok(Math.max(...positions) - Math.min(...positions) < 3, "caret, icon, label and status share one header line");
    await header.click();
    await page.getByText("核对人物连续性", { exact: true }).waitFor();
    assert.equal(await page.getByTestId("agent-subagent").count(), 2);
    assert.equal(await page.getByRole("button", { name: /查看结果/ }).count(), 0);
    assert.equal(await page.evaluate(() => window.__subagentFixture.calls.some(call => call.view === "result")), false);
    await page.evaluate(() => window.__subagentFixture.emitForeign());
    assert.equal(await page.getByText("不属于此会话").count(), 0);
    await header.click();
    await page.evaluate(() => window.__subagentFixture.complete());
    assert.equal(await header.getAttribute("aria-expanded"), "false", "progress cannot reopen the roster");
    assert.equal(await page.getByTestId("agent-subagent").count(), 0);
    await header.click();
    await page.getByText("需要核对", { exact: true }).waitFor();
    await page.getByTestId("agent-subagent").filter({ hasText: "核对人物连续性" }).click();
    await page.getByRole("heading", { name: "分镜建议", exact: true }).waitFor();
    await page.getByText("确认前镜中信封是否已拆开", { exact: true }).waitFor();
    await page.evaluate(() => window.__subagentFixture.fail());
    await page.getByTestId("agent-subagent").filter({ hasText: "检查镜头覆盖" }).click();
    await page.getByText("模型渠道暂不可用", { exact: true }).waitFor();
    await page.getByTestId("agent-subagent").filter({ hasText: "核对人物连续性" }).click();
    fs.mkdirSync(".tmp", { recursive: true });
    await page.getByTestId("agent-subagents").screenshot({ path: ".tmp/director-subagents-dark.png" });
    await page.getByRole("button", { name: "Theme", exact: true }).click();
    await page.getByRole("button", { name: "Language", exact: true }).click();
    await page.getByText("Needs review", { exact: true }).waitFor();
    await page.setViewportSize({ width: 390, height: 844 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.reload();
    await page.getByRole("button", { name: /^子代理任务/ }).click();
    await page.getByText("需要核对", { exact: true }).waitFor();
    assert.equal(await page.getByRole("heading", { name: "分镜建议" }).count(), 0, "refresh restores status without eagerly loading full results");
    await page.evaluate(() => window.__subagentFixture.holdResult());
    await page.getByTestId("agent-subagent").filter({ hasText: "核对人物连续性" }).click();
    await page.getByRole("button", { name: "Other director", exact: true }).click();
    await page.evaluate(() => window.__subagentFixture.releaseResult());
    await page.waitForFunction(() => !document.querySelector('[data-testid="agent-subagents"]'));
    assert.equal(await page.getByRole("heading", { name: "分镜建议" }).count(), 0, "late results cannot leak into another conversation");
    await page.getByRole("button", { name: "Original director", exact: true }).click();
    await page.getByRole("button", { name: /^子代理任务/ }).click();
    await page.getByText("核对人物连续性", { exact: true }).waitFor();
    await page.getByTestId("agent-subagent").filter({ hasText: "核对人物连续性" }).click();
    await page.getByRole("heading", { name: "分镜建议", exact: true }).waitFor();
    await page.evaluate(() => window.__subagentFixture.failList(true));
    await page.getByText("子代理状态暂时无法同步", { exact: true }).waitFor();
    await page.getByRole("button", { name: "重新读取", exact: true }).click();
    await page.getByText("子代理状态暂时无法同步", { exact: true }).waitFor();
    assert.equal(await page.getByRole("button", { name: /^子代理任务/ }).getAttribute("aria-expanded"), "true", "manual rereads must preserve the expanded roster");
    assert.equal(await page.getByTestId("agent-subagent").filter({ hasText: "核对人物连续性" }).getAttribute("aria-expanded"), "true");
    assert.equal(await page.getByRole("heading", { name: "分镜建议", exact: true }).count(), 1, "same-session rereads keep an already loaded result");
    await page.evaluate(() => window.__subagentFixture.failList(false));
    await page.evaluate(() => window.__subagentFixture.lifecycle({ binding: "bound", status: "succeeded", outcome: "partial", validity: "current", artifactHash: "a".repeat(64) }));
    await page.getByText("内容未完成", { exact: true }).waitFor();
    await page.evaluate(() => window.__subagentFixture.lifecycle({ outcome: "complete", validity: "stale" }));
    await page.getByText("输入已过期", { exact: true }).waitFor();
    await page.evaluate(() => window.__subagentFixture.lifecycle({ adoption: { operationId: "edit", revision: 8, sourceHash: "b".repeat(64), opsHash: "c".repeat(64) } }));
    await page.getByText("已采纳", { exact: true }).waitFor();
    await page.getByText("已采纳到制作修订 8", { exact: true }).waitFor();
    await page.reload();
    await page.getByRole("button", { name: /^子代理任务/ }).click();
    await page.getByText("已采纳", { exact: true }).waitFor();
    await page.getByTestId("agent-subagent").filter({ hasText: "核对人物连续性" }).click();
    await page.getByText("已采纳到制作修订 8", { exact: true }).waitFor();
    await page.evaluate(() => window.__subagentFixture.lifecycle({ status: "failed", adoption: undefined, recoverable: true }));
    await page.getByRole("button", { name: "读取原回合结果", exact: true }).click();
    assert.ok(await page.evaluate(() => window.__subagentFixture.calls.some(call => call.action === "recover" && call.taskId === "child-a")));
    assert.deepEqual(errors, []);
    console.log("PASS: empty/error-only hiding, one-line collapsed header, collapse preserved across progress, selected result/failure details, parent isolation, stale response protection, reload, bilingual themes and narrow screen.");
} finally { await browser.close(); }
