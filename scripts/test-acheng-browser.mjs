import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { chromium } from 'playwright';

const root = path.resolve(import.meta.dirname, '..');
const requireWeb = createRequire(path.join(root, 'web/package.json'));
const { unzipSync, strFromU8 } = requireWeb('fflate');
const { createServer } = await import(pathToFileURL(requireWeb.resolve('vite')).href);
const cache = fs.mkdtempSync(path.join(os.tmpdir(), 'acheng-browser-'));
process.env.CANVAS_TEST_VITE_CACHE = cache;
const server = await createServer({ root: path.join(root, 'web'), configFile: path.join(root, 'web/vite.config.ts'), server: { port: 0, host: '127.0.0.1', open: false }, cacheDir: cache });
let browser;
try {
  await server.listen(); const address = server.httpServer.address();
  browser = await chromium.launch({ headless: true });
  const page = await browser.newPage(); page.setDefaultTimeout(10000); const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('requestfailed', request => console.error('Browser request failed:', request.url(), request.failure()?.errorText));
  const mediaFixture = route => route.fulfill({ status: 200, contentType: 'image/svg+xml', body: '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="16"><rect width="24" height="16" fill="#789"/></svg>' });
  await page.route('http://127.0.0.1:17370/media/**', mediaFixture);
  await page.route(`http://127.0.0.1:${address.port}/media/**`, mediaFixture);
  await page.goto(`http://127.0.0.1:${address.port}/tests/acheng-production.html`);
  const evidence = page.getByLabel('evidence'); await evidence.waitFor();
  const read = async () => JSON.parse(await evidence.textContent());
  assert.equal((await read()).saves, 0);
  await page.getByRole('button', { name: '故事', exact: true }).click();
  const story = page.getByPlaceholder('场景正文与逐字对白');
  await story.fill('信使：你确定要把它交给我？\n守门人：我只答应把信带到。\n字幕外的远处汽笛响起。');
  await story.blur();
  await page.waitForFunction(() => JSON.parse(document.querySelector('output').textContent).director.source.script_scenes[0].text.includes('远处汽笛'));
  assert.equal((await read()).saves, 1);

  await page.getByRole('button', { name: '风格与资产', exact: true }).click();
  await page.getByRole('img', { name: 'STYLE_MOTHER · 码头晨雾' }).waitFor();
  await page.getByRole('button', { name: '查看审核原图' }).first().click();
  await page.getByRole('dialog').getByRole('img', { name: 'STYLE_MOTHER · 码头晨雾' }).waitFor();
  await page.locator('.ant-modal-close').last().click();
  await page.getByPlaceholder('审核理由').first().fill('已检查风格母图与角色一致性。');
  await page.getByRole('button', { name: '批准此版本' }).first().click();
  await page.waitForFunction(() => JSON.parse(document.querySelector('output').textContent).director.assets.STYLE_MOTHER.status === 'approved');

  await page.getByRole('button', { name: '镜头与片段', exact: true }).click();
  const switches = page.getByRole('switch');
  assert.equal(await switches.count(), 2);
  await switches.nth(0).click();
  await switches.nth(1).click();
  await page.getByRole('button', { name: '保存边界决定' }).click();
  assert.equal((await read()).director.boundaries[0].tailFrame, true);
  assert.equal((await read()).director.boundaries[0].motionContext, true);

  await page.getByRole('button', { name: '生产与交付', exact: true }).click();
  await page.getByText('完整编译提示词', { exact: true }).waitFor();
  const h3Details = page.locator('details').filter({ has: page.locator('summary').filter({ hasText: 'SEG1 · h3 · ready' }) }).first();
  await h3Details.locator('summary').click();
  assert.equal(await h3Details.evaluate(element => element.open), true);
  const compiledPrompt = await h3Details.locator('pre').textContent();
  assert.match(compiledPrompt, /\[Picture 1\] Dockside at dawn, a lone courier checks the sealed letter/);
  assert.equal(await h3Details.locator('video[aria-label="<Video 1>"]').count(), 1);
  assert.equal(await h3Details.locator('audio[aria-label="<Audio 1>"]').count(), 1);
  assert.equal(await h3Details.locator('video[aria-label="<Video 1>"]').evaluate(media => media.autoplay), false);
  await page.getByRole('button', { name: '生成此 Segment' }).first().click();
  assert.equal((await read()).batches[0].targets.length, 1);
  assert.equal((await read()).batches[0].status, 'pending');

  await page.getByRole('button', { name: '镜头与片段', exact: true }).click();
  await page.getByRole('combobox').first().click();
  await page.locator('.ant-select-item-option-content').filter({ hasText: '2. 守门人不松手' }).click();
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: '保存编组', exact: true }).first().click();
  await page.getByRole('dialog').getByRole('button', { name: /OK|确.*定/ }).click();
  await page.waitForFunction(() => JSON.parse(document.querySelector('output').textContent).director.source.segments.length === 1);
  assert.deepEqual((await read()).director.source.segments[0].shot_ids, ['s1', 's2']);
  assert.equal((await read()).director.source.shots[0].dialogues[0].text, '你确定要把它交给我？');
  assert.ok((await read()).director.artifacts.every(item => item.status === 'stale'));

  await page.getByRole('button', { name: '高级与历史', exact: true }).click();
  await page.locator('summary').filter({ hasText: '高级' }).click();
  await page.getByRole('button', { name: '导入或编辑 Acheng JSON', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByRole('textbox').fill('{invalid');
  await dialog.getByRole('button', { name: /OK|确.*定/ }).click();
  assert.match(await dialog.innerText(), /JSON|Unexpected|Expected/);
  await dialog.getByRole('button', { name: /Cancel|取.*消/ }).click();
  await page.getByRole('button', { name: '生产与交付', exact: true }).click();
  const bundleDownload = page.waitForEvent('download', { timeout: 30000 });
  await page.getByRole('button', { name: '导出提示词与交付包', exact: true }).click();
  const downloaded = await bundleDownload;
  const zip = unzipSync(fs.readFileSync(await downloaded.path()));
  assert.ok(zip['production.json']); assert.ok(zip['manifest.json']); assert.ok(zip['prompts/h3/SEG1.txt']); assert.ok(zip['references/001-Picture_1.bin']);
  const manifest = JSON.parse(strFromU8(zip['manifest.json']));
  const exportedProduction = JSON.parse(strFromU8(zip['production.json']));
  assert.equal(manifest.stage, 'partial'); assert.equal(manifest.sourceRevision, exportedProduction.revision); assert.ok(manifest.artifacts.length >= 4);
  await page.getByRole('button', { name: 'theme', exact: true }).click();
  await page.getByRole('button', { name: 'language', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ passed: true, scope: 'object workspaces, source edits, open-and-loaded media review, independent continuity, Shot/Segment timeline, full prompts, explicit generation, partial delivery ZIP and reference copies, advanced JSON validation, bilingual responsive UI' }));
} finally {
  await browser?.close(); await server.close();
  if (path.dirname(cache) !== os.tmpdir() || !path.basename(cache).startsWith('acheng-browser-')) throw new Error('Unexpected cleanup path');
  fs.rmSync(cache, { recursive: true, force: true });
}
